#!/usr/bin/env bash
# Снять распределение размеров файлов для корпуса C2 «Домашний каталог» (SPEC 17.3).
# Использование: c2-sizes.sh [каталог, по умолчанию $HOME] > c2-sizes.csv
#
# Сохраняются ТОЛЬКО размеры: ни имён, ни путей, ни времён. Выход — CSV `size,count`
# (сколько файлов точного размера `size` байт), по возрастанию размера; порядок обхода
# каталогов не сохраняется. Обход не заходит в другие файловые системы (-xdev) и не следует
# по симлинкам (find по умолчанию -P, симлинки не считаются файлами: -type f).
# Размер — видимый (st_size), у разреженных файлов он больше занятого. Жёсткие ссылки
# считаются столько раз, сколько у файла имён. Итоги и число ошибок чтения — в stderr.
set -euo pipefail

root=${1:-$HOME}
errs=$(mktemp)
trap 'rm -f "$errs"' EXIT

echo "size,count"
# find выходит с кодом 1 при любой ошибке чтения (нет прав и т. п.), это не повод бросать обход.
{ find "$root" -xdev -type f -printf '%s\n' 2>"$errs" || true; } | LC_ALL=C sort -n | LC_ALL=C uniq -c |
    awk '{ print $2 "," $1; files += $1; bytes += $1 * $2 }
         END { printf "C2: %d files, %d bytes\n", files, bytes > "/dev/stderr" }'
# Текст ошибок содержит пути, поэтому наружу выводится только число.
echo "C2: $(wc -l <"$errs") read errors (messages dropped, they contain paths)" >&2
